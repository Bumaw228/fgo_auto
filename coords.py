def team_dot_x(team_index):
    """回傳第 N 隊圓點的 x 座標（team_index 從 1 開始）"""
    gap = (TEAM_DOT_LAST_X - TEAM_DOT_FIRST_X) / float(TEAM_DOT_COUNT - 1)
    return int(TEAM_DOT_FIRST_X + (team_index - 1) * gap)

